// Generates public/js/data/items.js (the item IDs the Players page suggests
// for /give) from the `minecraft-data` dev dependency. Run with
// `npm run gen-items` after upgrading minecraft-data, and commit the output.
//
// Which version: the newest *release* of Minecraft Java Edition that the
// installed package knows (snapshots are skipped). Items are written without
// the "minecraft:" namespace, sorted, one per line. `air` is left out: it can't
// be given.
import { writeFileSync } from 'node:fs';
import minecraftData from 'minecraft-data';

const OUT = new URL('../public/js/data/items.js', import.meta.url);
const NOT_GIVABLE = new Set(['air']);

// supportedVersions.pc is ordered oldest to newest.
function newestRelease() {
  const supported = minecraftData.supportedVersions.pc;
  for (let i = supported.length - 1; i >= 0; i--) {
    const data = minecraftData(supported[i]);
    if (data?.version?.releaseType === 'release' && data.itemsArray?.length > 0) return data;
  }
  throw new Error('minecraft-data has no release version with items');
}

const data = newestRelease();
const items = [...new Set(data.itemsArray.map((item) => item.name))]
  .filter((name) => /^[a-z0-9_.]+$/.test(name) && !NOT_GIVABLE.has(name))
  .sort();

const source = `// GENERATED by scripts/gen-items.js from minecraft-data (Minecraft Java ${data.version.minecraftVersion}).
// Do not edit by hand: run \`npm run gen-items\`.
export const ITEMS = [
${items.map((name) => `  '${name}',`).join('\n')}
];
`;
writeFileSync(OUT, source);
console.log(`${items.length} items from Minecraft Java ${data.version.minecraftVersion} -> public/js/data/items.js`);
